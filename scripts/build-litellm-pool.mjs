// Regenerates the round-robin pool block inside litellm/config.yaml from the
// OLLAMA_KEY_* variables in .env. Each non-empty key becomes another "ollama-pool"
// deployment; LiteLLM then load-balances (round-robins) requests across them.
// Keys are referenced via os.environ/... — they are NEVER written into config.yaml.
//
// Usage (from repo root, with .env present):
//   node --env-file=.env scripts/build-litellm-pool.mjs
import { readFileSync, writeFileSync } from "node:fs";

const CFG = new URL("../litellm/config.yaml", import.meta.url);
const base = (process.env.OLLAMA_POOL_BASE || "https://ollama.com/v1").trim();
const model = (process.env.OLLAMA_POOL_MODEL || "gpt-oss:120b").trim();

const keyVars = Object.keys(process.env)
  .filter((k) => /^OLLAMA_KEY_\d+$/.test(k) && (process.env[k] || "").trim())
  .sort((a, b) => Number(a.split("_").pop()) - Number(b.split("_").pop()));

const START = "  # >>> POOL START (generated by scripts/build-litellm-pool.mjs)";
const END = "  # <<< POOL END";

const entries = keyVars.length
  ? keyVars
      .map(
        (k) =>
          `  - model_name: ollama-pool\n    litellm_params:\n      model: openai/${model}\n      api_base: ${base}\n      api_key: os.environ/${k}`,
      )
      .join("\n")
  : "  # (no OLLAMA_KEY_* set in .env yet)";

const block = `${START}\n${entries}\n${END}`;

let cfg = readFileSync(CFG, "utf8");
if (cfg.includes(START)) {
  cfg = cfg.replace(new RegExp(`${START}[\\s\\S]*?${END}`), block);
} else {
  // Insert as more model_list items, right before litellm_settings.
  cfg = cfg.replace(/\nlitellm_settings:/, `\n${block}\n\nlitellm_settings:`);
}
writeFileSync(CFG, cfg);
console.log(`ollama-pool: ${keyVars.length} key(s) | model=openai/${model} | base=${base}`);
